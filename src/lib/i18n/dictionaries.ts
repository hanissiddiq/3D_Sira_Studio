/** Pilih teks sesuai bahasa; jatuh ke bahasa lain jika kosong. */
export function pick(lang: Lang, textId: string | null | undefined, textEn: string | null | undefined) {
  const a = lang === "en" ? textEn : textId;
  const b = lang === "en" ? textId : textEn;
  return a || b || "";
}
